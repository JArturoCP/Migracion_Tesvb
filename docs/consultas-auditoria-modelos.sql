-- Auditoría de metadatos: todas las sentencias son SELECT, sin filas de negocio.
SELECT VERSION() AS version, DATABASE() AS selected_database, @@sql_mode AS sql_mode;
SELECT TABLE_NAME, TABLE_TYPE, ENGINE
FROM information_schema.TABLES WHERE TABLE_SCHEMA = 'tesvb' ORDER BY TABLE_NAME;
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, COLUMN_TYPE, IS_NULLABLE,
       COLUMN_DEFAULT, COLUMN_KEY, EXTRA, DATETIME_PRECISION
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = 'tesvb'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, ORDINAL_POSITION,
       REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA = 'tesvb'
ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION;
